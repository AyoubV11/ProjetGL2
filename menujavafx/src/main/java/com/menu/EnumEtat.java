package com.menu;

/**
 * Énumération représentant les différents états possibles d'une case ou d'un élément du jeu.
 * <p>
 * Cette énumération définit trois états:
 * <ul>
 *   <li>VIDE: Représente un état vide ou non marqué</li>
 *   <li>TRAIT: Représente un état marqué par un trait</li>
 *   <li>CROIX: Représente un état marqué par une croix</li>
 * </ul>
 * </p>
 */
public enum EnumEtat {
    VIDE, TRAIT, CROIX
}