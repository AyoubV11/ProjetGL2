package com.menu;

/**
 * Énumération représentant les orientations possibles.
 * <p>
 * Cette énumération définit deux orientations:
 * <ul>
 *   <li>HORIZONTAL: Représente une orientation horizontale (de gauche à droite)</li>
 *   <li>VERTICAL: Représente une orientation verticale (de haut en bas)</li>
 * </ul>
 * </p>
 */
public enum EnumOrientation {
    HORIZONTAL, VERTICAL;
}